#!/usr/bin/env python
"""Rebuild headline audit tables from packaged SAFE-KV summaries."""

from __future__ import annotations

import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reproduction_runs" / "results_paper"


EXTERNAL_METHODS = [
    ("Prefix", "prefix_conditioned_naive_global"),
    ("Query K1", "query_similarity_suffix_closure_k1"),
    ("Query K2", "query_similarity_suffix_closure_k2"),
    ("Risk K1", "risk_guided_suffix_closure_k1"),
    ("Hybrid K1", "hybrid_query_risk_union_suffix_k1"),
    ("Risk K2", "risk_guided_suffix_closure_k2"),
    ("Random K2", "random_suffix_closure_k2_seeded"),
]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    write_external_7b()
    write_mistral()
    write_latency()
    write_index()
    print(f"Wrote headline reproduction tables to {OUT}")


def write_external_7b() -> None:
    rows = []
    for dataset, summary_path in [
        ("HotpotQA-500", "results/acl_qwen25_7b_hotpotqa_suffix_main_500/answer_eval_summary.json"),
        ("2Wiki-500", "results/acl_qwen25_7b_2wiki_suffix_main_500/answer_eval_summary.json"),
    ]:
        summary = read_json(summary_path)
        for label, method in EXTERNAL_METHODS:
            if method not in summary["method_level"]:
                continue
            rows.append(metric_row(dataset, label, method, summary))
    write_csv(OUT / "external_7b_answer_table.csv", rows)


def write_mistral() -> None:
    summary = read_json("results/acl_mistral7b_noisy_suffix_250_balanced/answer_eval_summary.json")
    rows = [
        metric_row("Mistral-7B noisy-250", method, method_key, summary)
        for method, method_key in [
            ("Prefix", "prefix_conditioned_naive_global"),
            ("Query K1", "query_similarity_suffix_closure_k1"),
            ("Risk K1", "risk_guided_suffix_closure_k1"),
            ("Hybrid K1", "hybrid_query_risk_union_suffix_k1"),
            ("Risk K2", "risk_guided_suffix_closure_k2"),
        ]
    ]
    write_csv(OUT / "mistral_cross_model_table.csv", rows)


def write_latency() -> None:
    rows = []
    for dataset, summary_path, methods in [
        (
            "2Wiki-50",
            "results/acl_qwen25_7b_2wiki_latency_suffix_50_with_hybrid/latency_summary.json",
            [
                ("Full prefill", "full_prefill_forward"),
                ("Risk suffix K1", "risk_suffix_k1_recompute_plus_query"),
                ("Hybrid suffix K1", "hybrid_query_risk_union_suffix_k1_recompute_plus_query"),
                ("Risk suffix K2", "risk_suffix_k2_recompute_plus_query"),
            ],
        ),
        (
            "Noise64-20",
            "results/acl_qwen25_7b_noise64_latency_suffix_20_with_hybrid/latency_summary.json",
            [
                ("Full prefill", "full_prefill_forward"),
                ("Risk suffix K1", "risk_suffix_k1_recompute_plus_query"),
                ("Hybrid suffix K1", "hybrid_query_risk_union_suffix_k1_recompute_plus_query"),
                ("Risk suffix K2", "risk_suffix_k2_recompute_plus_query"),
            ],
        ),
    ]:
        summary = read_json(summary_path)
        for label, method in methods:
            row = summary["method_level"][method]
            rows.append(
                {
                    "dataset": dataset,
                    "method": label,
                    "avg_wall_time_s": row["avg_wall_time_s"],
                    "median_wall_time_s": row["median_wall_time_s"],
                    "p95_wall_time_s": row["p95_wall_time_s"],
                    "avg_peak_cuda_memory_mb": row["avg_peak_cuda_memory_mb"],
                    "avg_patched_token_ratio": row["avg_patched_token_ratio"],
                }
            )
    write_csv(OUT / "latency_sanity_table.csv", rows)


def metric_row(dataset: str, label: str, method: str, summary: dict) -> dict:
    row = summary["method_level"][method]
    return {
        "dataset": dataset,
        "method": label,
        "method_key": method,
        "answer_equivalence_to_full_prefill": row["answer_equivalence_to_full_prefill"],
        "gold_exact_match": row["gold_exact_match"],
        "gold_token_f1": row["gold_token_f1"],
        "answer_changed_and_gold_wrong_count": row["answer_changed_and_gold_wrong_count"],
        "avg_patched_token_ratio": row["avg_patched_token_ratio"],
        "avg_first_token_kl": row["avg_first_token_kl"],
    }


def write_index() -> None:
    text = """# Rebuilt Headline Tables

This directory is generated by `scripts/rebuild_headline_tables.py` from packaged JSON summaries.

- `external_7b_answer_table.csv`
- `mistral_cross_model_table.csv`
- `latency_sanity_table.csv`

The paper-facing LaTeX/Markdown mirrors remain in `paper_reference/final_tables/`.
"""
    (OUT / "README.md").write_text(text, encoding="utf-8")


def read_json(relative: str) -> dict:
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        raise ValueError(f"no rows for {path}")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


if __name__ == "__main__":
    main()
